static uint32_t findMemoryType(uint32_t typeFilter, VkMemoryPropertyFlags props) {
    VkPhysicalDeviceMemoryProperties memProps;
    vkGetPhysicalDeviceMemoryProperties(g_physDev, &memProps);
    for (uint32_t i = 0; i < memProps.memoryTypeCount; i++) {
        if ((typeFilter & (1 << i)) && (memProps.memoryTypes[i].propertyFlags & props) == props)
            return i;
    }
    for (uint32_t i = 0; i < memProps.memoryTypeCount; i++) {
        if (typeFilter & (1 << i))
            return i;
    }
    return UINT32_MAX;
}

static bool createBuffer(VkDeviceSize size, VkBufferUsageFlags usage, VkBuffer* buf, VkDeviceMemory* mem) {
    VkBufferCreateInfo ci{};
    ci.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
    ci.size = size;
    ci.usage = usage;
    ci.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    if (vkCreateBuffer(g_device, &ci, nullptr, buf) != VK_SUCCESS) return false;
    VkMemoryRequirements reqs;
    vkGetBufferMemoryRequirements(g_device, *buf, &reqs);
    uint32_t memTypeIdx = findMemoryType(reqs.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    if (memTypeIdx == UINT32_MAX) { vkDestroyBuffer(g_device, *buf, nullptr); *buf = VK_NULL_HANDLE; return false; }
    VkMemoryAllocateInfo ai{};
    ai.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    ai.allocationSize = reqs.size;
    ai.memoryTypeIndex = memTypeIdx;
    if (vkAllocateMemory(g_device, &ai, nullptr, mem) != VK_SUCCESS) { vkDestroyBuffer(g_device, *buf, nullptr); *buf = VK_NULL_HANDLE; return false; }
    if (vkBindBufferMemory(g_device, *buf, *mem, 0) != VK_SUCCESS) {
        vkFreeMemory(g_device, *mem, nullptr); *mem = VK_NULL_HANDLE;
        vkDestroyBuffer(g_device, *buf, nullptr); *buf = VK_NULL_HANDLE;
        return false;
    }
    return true;
}

static bool createInstance() {
#if !HAS_VULKAN
    LOGE("Vulkan not linked at build time");
    return false;
#endif
    void* handle = dlopen("libvulkan.so", RTLD_LAZY | RTLD_LOCAL);
    if (!handle) {
        LOGE("dlopen libvulkan.so failed: %s", dlerror());
        return false;
    }
    dlclose(handle);

    VkApplicationInfo appInfo{};
    appInfo.sType = VK_STRUCTURE_TYPE_APPLICATION_INFO;
    appInfo.pApplicationName = "FinalBenchmark2";
    appInfo.applicationVersion = VK_MAKE_VERSION(1, 0, 0);
    appInfo.apiVersion = VK_API_VERSION_1_1;

    VkInstanceCreateInfo ci{};
    ci.sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO;
    ci.pApplicationInfo = &appInfo;
    VkResult res = vkCreateInstance(&ci, nullptr, &g_instance);
    if (res != VK_SUCCESS) {
        LOGE("vkCreateInstance failed: %d", (int)res);
        return false;
    }
    return true;
}

static bool pickPhysicalDevice() {
    uint32_t count = 0;
    vkEnumeratePhysicalDevices(g_instance, &count, nullptr);
    if (count == 0) return false;
    std::vector<VkPhysicalDevice> devs(count);
    vkEnumeratePhysicalDevices(g_instance, &count, devs.data());
    g_physDev = devs[0];
    VkPhysicalDeviceProperties props{};
    vkGetPhysicalDeviceProperties(g_physDev, &props);
    g_gpuName = props.deviceName;
    g_timestampPeriod = props.limits.timestampPeriod;
    LOGI("Vulkan GPU: %s | timestampPeriod=%.2f ns", g_gpuName.c_str(), g_timestampPeriod);
    return true;
}

static bool createDevice() {
    uint32_t qfCount = 0;
    vkGetPhysicalDeviceQueueFamilyProperties(g_physDev, &qfCount, nullptr);
    std::vector<VkQueueFamilyProperties> qfProps(qfCount);
    vkGetPhysicalDeviceQueueFamilyProperties(g_physDev, &qfCount, qfProps.data());

    g_queueFamily = UINT32_MAX;
    for (uint32_t i = 0; i < qfCount; i++) {
        if (qfProps[i].queueFlags & VK_QUEUE_COMPUTE_BIT) {
            g_queueFamily = i;
            g_timestampBits = qfProps[i].timestampValidBits;
            break;
        }
    }
    if (g_queueFamily == UINT32_MAX) return false;

    float prio = 1.0f;
    VkDeviceQueueCreateInfo qci{};
    qci.sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO;
    qci.queueFamilyIndex = g_queueFamily;
    qci.queueCount = 1;
    qci.pQueuePriorities = &prio;

    VkDeviceCreateInfo dci{};
    dci.sType = VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO;
    dci.queueCreateInfoCount = 1;
    dci.pQueueCreateInfos = &qci;
    if (vkCreateDevice(g_physDev, &dci, nullptr, &g_device) != VK_SUCCESS) return false;
    vkGetDeviceQueue(g_device, g_queueFamily, 0, &g_queue);
    return true;
}

static bool createCommandPool() {
    VkCommandPoolCreateInfo ci{};
    ci.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
    ci.queueFamilyIndex = g_queueFamily;
    ci.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
    if (vkCreateCommandPool(g_device, &ci, nullptr, &g_cmdPool) != VK_SUCCESS) return false;
    VkCommandBufferAllocateInfo ai{};
    ai.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
    ai.commandPool = g_cmdPool;
    ai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
    ai.commandBufferCount = 1;
    return vkAllocateCommandBuffers(g_device, &ai, &g_cmdBuf) == VK_SUCCESS;
}

static bool createComputePipeline(int sceneId) {
    const SceneConfig& cfg = SCENE_CFG[sceneId];
    if (cfg.spirvLen == 0 || cfg.spirvLen % 4 != 0) {
        LOGE("Scene %d: invalid SPIR-V size %u", sceneId, cfg.spirvLen);
        return false;
    }
    VkShaderModuleCreateInfo smci{};
    smci.sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO;
    smci.codeSize = cfg.spirvLen;
    smci.pCode = reinterpret_cast<const uint32_t*>(cfg.spirv);
    VkResult smRes = vkCreateShaderModule(g_device, &smci, nullptr, &g_module[sceneId]);
    if (smRes != VK_SUCCESS) {
        LOGE("Scene %d: vkCreateShaderModule failed: %d", sceneId, (int)smRes);
        return false;
    }

    // Create Descriptor Set Layout
    VkDescriptorSetLayoutBinding layoutBinding{};
    layoutBinding.binding = 0;
    layoutBinding.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
    layoutBinding.descriptorCount = 1;
    layoutBinding.stageFlags = VK_SHADER_STAGE_COMPUTE_BIT;

    VkDescriptorSetLayoutCreateInfo dslci{};
    dslci.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
    dslci.bindingCount = 1;
    dslci.pBindings = &layoutBinding;
    if (vkCreateDescriptorSetLayout(g_device, &dslci, nullptr, &g_descLayout[sceneId]) != VK_SUCCESS) return false;

    VkPushConstantRange pcRange{};
    pcRange.stageFlags = VK_SHADER_STAGE_COMPUTE_BIT;
    pcRange.offset = 0;
    pcRange.size = cfg.pushConstSize;

    VkPipelineLayoutCreateInfo plci{};
    plci.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
    plci.setLayoutCount = 1;
    plci.pSetLayouts = &g_descLayout[sceneId];
    if (cfg.hasPushConst) {
        plci.pushConstantRangeCount = 1;
        plci.pPushConstantRanges = &pcRange;
    }
    if (vkCreatePipelineLayout(g_device, &plci, nullptr, &g_pipeLayout[sceneId]) != VK_SUCCESS) return false;

    VkPipelineShaderStageCreateInfo stage{};
    stage.sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    stage.stage = VK_SHADER_STAGE_COMPUTE_BIT;
    stage.module = g_module[sceneId];
    stage.pName = "main";

    VkComputePipelineCreateInfo cpci{};
    cpci.sType = VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO;
    cpci.stage = stage;
    cpci.layout = g_pipeLayout[sceneId];
    VkResult cpRes = vkCreateComputePipelines(g_device, VK_NULL_HANDLE, 1, &cpci, nullptr, &g_pipeline[sceneId]);
    if (cpRes != VK_SUCCESS) {
        LOGE("Scene %d: vkCreateComputePipelines failed: %d", sceneId, (int)cpRes);
        return false;
    }
    return true;
}

static bool createQueryPool() {
    if (g_timestampBits == 0) return false;
    VkQueryPoolCreateInfo qpci{};
    qpci.sType = VK_STRUCTURE_TYPE_QUERY_POOL_CREATE_INFO;
    qpci.queryType = VK_QUERY_TYPE_TIMESTAMP;
    qpci.queryCount = 2;
    return vkCreateQueryPool(g_device, &qpci, nullptr, &g_queryPool) == VK_SUCCESS;
}

static float dispatchAndTime(int sceneId) {
    const SceneConfig& cfg = SCENE_CFG[sceneId];
    VkCommandBufferBeginInfo bi{};
    bi.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
    bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
    vkBeginCommandBuffer(g_cmdBuf, &bi);
    if (g_queryPool != VK_NULL_HANDLE) {
        vkCmdResetQueryPool(g_cmdBuf, g_queryPool, 0, 2);
        vkCmdWriteTimestamp(g_cmdBuf, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, g_queryPool, 0);
    }
    vkCmdBindPipeline(g_cmdBuf, VK_PIPELINE_BIND_POINT_COMPUTE, g_pipeline[sceneId]);
    vkCmdBindDescriptorSets(g_cmdBuf, VK_PIPELINE_BIND_POINT_COMPUTE, g_pipeLayout[sceneId], 0, 1, &g_descSet[sceneId], 0, nullptr);

    // Push constants per scene
    if (sceneId == 0) { // Julia 4K, high iter
        float pc[3] = {-0.7f, 0.27015f, 512.0f};
        vkCmdPushConstants(g_cmdBuf, g_pipeLayout[sceneId], VK_SHADER_STAGE_COMPUTE_BIT, 0, cfg.pushConstSize, pc);
    } else if (sceneId == 1) { // Mandelbrot 4K, high iter
        int pc = 2048;
        vkCmdPushConstants(g_cmdBuf, g_pipeLayout[sceneId], VK_SHADER_STAGE_COMPUTE_BIT, 0, cfg.pushConstSize, &pc);
    } else if (sceneId == 2) { // GEMM 1024x1024
        int pc = 1024;
        vkCmdPushConstants(g_cmdBuf, g_pipeLayout[sceneId], VK_SHADER_STAGE_COMPUTE_BIT, 0, cfg.pushConstSize, &pc);
    } else if (sceneId == 3) { // N-body
        float pc[2] = {0.001f, 4096.0f};
        vkCmdPushConstants(g_cmdBuf, g_pipeLayout[sceneId], VK_SHADER_STAGE_COMPUTE_BIT, 0, cfg.pushConstSize, pc);
    }

    vkCmdDispatch(g_cmdBuf, cfg.groupsX, cfg.groupsY, cfg.groupsZ);
    if (g_queryPool != VK_NULL_HANDLE)
        vkCmdWriteTimestamp(g_cmdBuf, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT, g_queryPool, 1);
    vkEndCommandBuffer(g_cmdBuf);

    // Wall-clock timing around the ACTUAL dispatch (reliable on all GPUs)
    auto cpu0 = std::chrono::high_resolution_clock::now();

    VkSubmitInfo si{};
    si.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
    si.commandBufferCount = 1;
    si.pCommandBuffers = &g_cmdBuf;
    vkQueueSubmit(g_queue, 1, &si, VK_NULL_HANDLE);
    vkQueueWaitIdle(g_queue);

    auto cpu1 = std::chrono::high_resolution_clock::now();
    float cpuMs = std::chrono::duration<float, std::milli>(cpu1 - cpu0).count();

    // Try GPU timestamp query first (accurate on Adreno/PowerVR)
    if (g_queryPool != VK_NULL_HANDLE) {
        uint64_t timestamps[2] = {0, 0};
        VkResult r = vkGetQueryPoolResults(g_device, g_queryPool, 0, 2,
            sizeof(timestamps), timestamps, sizeof(uint64_t),
            VK_QUERY_RESULT_64_BIT | VK_QUERY_RESULT_WAIT_BIT);
        if (r == VK_SUCCESS && timestamps[1] > timestamps[0]) {
            float gpuMs = float(timestamps[1] - timestamps[0]) * g_timestampPeriod * 1e-6f;
            // Sanity: reject values below 0.01ms (would mean 100K+ FPS — impossible)
            if (gpuMs > 0.01f && gpuMs < 10000.0f) return gpuMs;
        }
    }
    // Fallback: wall-clock time of the real dispatch (works on Mali, all GPUs)
    // Sanity: reject values below 0.01ms (would mean 100K+ FPS — impossible)
    if (cpuMs > 0.01f && cpuMs < 10000.0f) return cpuMs;
    return -1.0f;  // signal failure to caller
}

